// Helper to generate hourly sequence
function generateHourly(
  baseTemp: number,
  baseRain: number,
  condition: string,
  rainProfile: number[]
) {
  const hours = ['Now', '1 PM', '2 PM', '3 PM', '4 PM', '5 PM', '6 PM', '7 PM', '8 PM', '9 PM', '10 PM', '11 PM', '12 AM'];
  return hours.map((time, i) => {
    const rain = rainProfile[i] !== undefined ? rainProfile[i] : baseRain;
    const tempOffset = Math.sin((i / 12) * Math.PI) * 4 - (i > 7 ? (i - 7) * 0.8 : 0);
    const temp = Math.round(baseTemp + tempOffset);
    let cond: any = condition;
    let condText = 'Clear';
    if (rain > 60) {
      cond = 'heavy-rain';
      condText = 'Heavy Rain';
    } else if (rain > 30) {
      cond = 'rain';
      condText = 'Light Rain';
    } else if (i > 8) {
      cond = 'partly-cloudy';
      condText = 'Partly Cloudy';
    }

    return {
      time,
      hour: 12 + i,
      temp,
      feelsLike: temp + 2,
      condition: cond,
      conditionText: condText,
      rainProb: rain,
      uvIndex: i >= 1 && i <= 5 ? Math.max(1, 8 - i) : 1,
      windSpeed: Math.round(12 + Math.random() * 6),
      aqi: 68 + i * 2,
    };
  });
}

